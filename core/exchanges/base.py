"""Common exchange interface. Strategies only talk to this, never to a venue SDK directly."""

from __future__ import annotations

import abc
from dataclasses import dataclass
from decimal import Decimal

from core.models import Market, OrderBook, Side, Venue


class ExchangeError(Exception):
    """Non-retryable venue error (bad request, auth, not found)."""


class TradingDisabled(ExchangeError):
    """Raised when a trading call is made on a client not configured for trading."""


@dataclass(frozen=True)
class OrderRequest:
    market_id: str
    side: Side                  # outcome bought: YES or NO
    contracts: Decimal
    limit_price: Decimal        # price of the outcome being bought
    client_order_id: str        # idempotency key, generated by core/execution
    time_in_force: str = "ioc"  # ioc | gtc | fok


class Exchange(abc.ABC):
    venue: Venue

    # ---- public market data ----
    @abc.abstractmethod
    async def get_market(self, market_id: str) -> Market: ...

    @abc.abstractmethod
    async def get_orderbook(self, market_id: str) -> OrderBook: ...

    async def get_orderbooks(self, market_ids: list[str]) -> dict[str, OrderBook]:
        """Default: one call per market. Venues with a batch endpoint override this."""
        return {m: await self.get_orderbook(m) for m in market_ids}

    # ---- trading (implemented in the demo/execution phase) ----
    async def place_order(self, req: OrderRequest) -> dict:
        raise TradingDisabled(f"{self.venue.value}: trading not enabled in this build")

    async def cancel_order(self, order_id: str) -> None:
        raise TradingDisabled(f"{self.venue.value}: trading not enabled in this build")

    async def cancel_all_orders(self) -> int:
        raise TradingDisabled(f"{self.venue.value}: trading not enabled in this build")

    async def get_positions(self) -> list[dict]:
        raise TradingDisabled(f"{self.venue.value}: trading not enabled in this build")

    async def aclose(self) -> None:
        return None
